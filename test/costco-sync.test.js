const assert = require("assert");
const { digitalReceiptHtml, identityFromClaims, injectSyncToolbar, syncDateRange } = require("../electron/costco-sync");

const range = syncDateRange(new Date("2026-07-16T12:00:00Z"));
assert.equal(range.endDate, "2026-07-16");
assert.equal(range.startDate, "2023-06-01");

const html = digitalReceiptHtml({
  transactionDate: "2026-07-15",
  transactionNumber: "123",
  transactionBarcode: "abc",
  warehouseShortName: "RICHMOND",
  warehouseNumber: "501",
  warehouseCountry: "CA",
  totalItemCount: 2,
  subTotal: 37.98,
  taxes: 1.82,
  total: 39.8,
  itemArray: [{ itemNumber: "1969525", itemDescription01: "K.SPADE PJ", itemUnitPriceAmount: 23.99, amount: 47.98, taxFlag: "B" }],
  couponArray: [{ associatedItemNumber: "1969525", amountCoupon: 5 }, { associatedItemNumber: "1969525", amountCoupon: 5 }]
});
assert(html.includes("K.SPADE PJ"));
assert(html.includes('class="number">2</td>'));
assert(html.includes("Costco Receipt Organizer archive"));
assert(html.includes("local archive copy generated by Costco Receipt Organizer"));

assert.deepEqual(identityFromClaims({ email: "member@example.com" }, [{ membershipNumber: "123456789012" }], "US"), {
  email: "member@example.com",
  membershipNumber: "123456789012",
  market: "US"
});

const injectedScripts = [];
injectSyncToolbar({ executeJavaScript: async script => injectedScripts.push(script) }, {
  market: "US",
  accountLabel: "member@example.com · Member 123456789012",
  status: "Sync is up to date",
  complete: true
}).then(() => {
  assert.equal(injectedScripts.length, 1);
  assert(injectedScripts[0].includes("receipt-sync://close"));
  assert(injectedScripts[0].includes("Costco United States"));
  assert(injectedScripts[0].includes("model.complete ? 'Done' : 'Close'"));
  console.log("Costco sync helper tests passed");
}).catch(error => {
  console.error(error);
  process.exitCode = 1;
});
